/**
 * Generate component prop allowlists from the installed @cloudflare/kumo.
 *
 * Colour-token allowlists used to be generated here too. They are gone:
 * validating class names against a hand-extracted token list has been replaced
 * by `eslint-plugin-better-tailwindcss`, which resolves the real Tailwind
 * config (see `.oxlintrc.json`). Component props have no equivalent there, so
 * they stay.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const registryPath = path.resolve(rootDir, 'node_modules/@cloudflare/kumo/ai/component-registry.json');

if (!fs.existsSync(registryPath)) {
  console.error(`Error: Kumo component registry not found at ${registryPath}.`);
  process.exit(1);
}

const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'));

const componentProps = {};

function processComponent(name, compObj) {
  if (!compObj.props) return;
  for (const [propName, propObj] of Object.entries(compObj.props)) {
    if (propObj.type === 'enum' && Array.isArray(propObj.values) && propObj.values.length > 0) {
      const cleanValues = propObj.values.filter((v) => typeof v === 'string' && v.length > 0);
      if (cleanValues.length > 0) {
        if (!componentProps[name]) componentProps[name] = {};
        componentProps[name][propName] = cleanValues;
      }
    }
  }
}

for (const [compName, compObj] of Object.entries(registry.components)) {
  processComponent(compName, compObj);
  if (compObj.subComponents) {
    for (const [subName, subObj] of Object.entries(compObj.subComponents)) {
      processComponent(`${compName}.${subName}`, subObj);
    }
  }
}

// 1. JSON for the JavaScript fallback engine
const jsonPath = path.resolve(rootDir, 'packages/vite-plus-kumo/generated_allowlists.json');
fs.writeFileSync(jsonPath, JSON.stringify({ componentProps }, null, 2) + '\n');
console.log(`Generated JS allowlists: ${jsonPath}`);

// 2. Rust source for the native engine
const rustLines = [];
rustLines.push('// AUTO-GENERATED BY scripts/generate-allowlists.mjs - DO NOT EDIT DIRECTLY');
rustLines.push('use lazy_static::lazy_static;');
rustLines.push('use std::collections::{HashSet, HashMap};');
rustLines.push('');
rustLines.push('lazy_static! {');
rustLines.push("    pub static ref COMPONENT_PROP_ALLOWLIST: HashMap<&'static str, HashMap<&'static str, HashSet<&'static str>>> = {");
rustLines.push("        let mut map: HashMap<&'static str, HashMap<&'static str, HashSet<&'static str>>> = HashMap::new();");

for (const [comp, props] of Object.entries(componentProps)) {
  rustLines.push('        {');
  rustLines.push('            let mut comp_map = HashMap::new();');
  for (const [prop, values] of Object.entries(props)) {
    rustLines.push('            {');
    rustLines.push('                let mut set = HashSet::new();');
    for (const val of values) {
      rustLines.push(`                set.insert(${JSON.stringify(val)});`);
    }
    rustLines.push(`                comp_map.insert(${JSON.stringify(prop)}, set);`);
    rustLines.push('            }');
  }
  rustLines.push(`            map.insert(${JSON.stringify(comp)}, comp_map);`);
  rustLines.push('        }');
}

rustLines.push('        map');
rustLines.push('    };');
rustLines.push('}');
rustLines.push('');
rustLines.push("pub fn get_valid_prop_values(component: &str, prop: &str) -> Option<&'static HashSet<&'static str>> {");
rustLines.push('    COMPONENT_PROP_ALLOWLIST.get(component).and_then(|props| props.get(prop))');
rustLines.push('}');
rustLines.push('');

const rustPath = path.resolve(rootDir, 'crates/vite-plus-kumo/src/rules/generated_allowlists.rs');
fs.writeFileSync(rustPath, rustLines.join('\n'));
console.log(`Generated Rust allowlists: ${rustPath}`);
